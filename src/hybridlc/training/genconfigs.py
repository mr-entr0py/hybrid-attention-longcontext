"""Generate ``configs/model/<scale>/<name>.yaml`` for every named configuration (protocol §3.2).

    python -m hybridlc.training.genconfigs            # (re)write configs/model/** and configs/experiments/feas/**
    python -m hybridlc.training.genconfigs --check    # exit 1 if any file is missing or stale

Each file holds the full ``ModelConfig`` field dict (``fields``) produced by
``ModelConfig.for_scale(scale, name)``, plus informational keys (k, tier, pattern). The fields — not
the name — are what the trainer instantiates and hashes, so a model YAML is a frozen, reviewable copy
of the protocol table. Placement "middle" arms are the composition arms and are not duplicated.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

import yaml

from .compat import REPO_ROOT

SCALES = ("D384", "D512")

#: (name, tier, overrides) — protocol §3.2 tables. k* is not known before S4, so the k*-dependent
#: arms are generated for every k* ∈ {1, 2, 3}.
NAMED: list[tuple[str, str, dict[str, Any]]] = [
    ("C0", "A", {}), ("C1", "A", {}), ("C2", "B", {}), ("C3", "A", {}), ("C4", "C", {}),
    ("C6", "B", {}), ("C12", "A", {}),
    *[(f"P{k}-{w}", "B", {}) for k in (1, 2, 3) for w in ("early", "late")],
    ("X-gc12", "A", {}), ("X-gc1", "B", {}), ("X-gc3", "B", {}),
    ("X-nope3", "A", {}), ("X-nope12", "A", {}),
    ("X-E0", "B", {}), ("X-E1", "B", {}), ("X-E2", "B", {}), ("X-E3", "B", {}),
    ("O-gla0", "C", {}), ("O-gla1", "C", {}), ("O-gla2", "C", {}), ("O-gla3", "C", {}),
    ("O-nc0", "C", {}), ("O-nc1", "C", {}), ("O-nc2", "C", {}), ("O-nc3", "C", {}),
    # SSMax (U-03): FEAS arm at k = 12; the non-chosen variant runs at k ∈ {3, 12} in Tier C.
    ("C12ssmax", "FEAS", {"base": "C12", "ssmax": True}),
    ("C3ssmax", "C", {"base": "C3", "ssmax": True}),
]

HEADER = ("# GENERATED by `python -m hybridlc.training.genconfigs` from hybridlc.models (protocol §3.2).\n"
          "# Do not edit by hand; regenerate instead. `fields` is what the trainer instantiates and hashes.\n")


def model_doc(scale: str, name: str, tier: str, overrides: dict[str, Any]) -> dict[str, Any]:
    from hybridlc.models.config import ModelConfig

    ov = dict(overrides)
    base = ov.pop("base", name)
    cfg = ModelConfig.for_scale(scale, base, **ov)
    cfg.name = name
    fields = cfg.to_dict()
    return {"name": name, "scale": scale, "k": cfg.k, "tier": tier, "pattern": cfg.pattern, "fields": fields}


def render(doc: dict[str, Any]) -> str:
    return HEADER + yaml.safe_dump(doc, sort_keys=False, default_flow_style=False, width=120)


# ---------------------------------------------------------------------------------- FEAS run YAMLs
#: S2 FEAS-384 design (plan.yaml stage S2; PI rulings §10 item 10, task T21). Generated, never hand-edited.
FEAS_SCALE = "D384"
FEAS_SEEDS = (101, 102)
FEAS_CONFIGS = ("C0", "C12")
FEAS_BRANCHES = ("30M", "90M")
FEAS_LR = 2.0e-3                 # provisional eta (D034); FEAS precedes the LR sweep
FEAS_FALLBACK_LR = 1.4e-3        # D034: a diverging FEAS run restarts once from scratch at 1.4e-3
FEAS_SSMAX = ("C12ssmax", 101, ("30M",))   # U-03 arm: k = 12, seed 101, small branch only
FEAS_DIR = "configs/experiments/feas"

FEAS_HEADER = ("# GENERATED by `python -m hybridlc.training.genconfigs` (S2 FEAS-384 design: plan.yaml stage S2;\n"
               "# PI rulings 2026-11-10 §10 item 10). Do not edit by hand; regenerate instead.\n")


def _bname(branch: str) -> str:
    return "B" + branch[:-1].zfill(3)        # 30M -> B030, 90M -> B090 (plan ids)


def feas_run_docs() -> dict[str, dict[str, Any]]:
    """File name -> run YAML document for every FEAS-384 run (Stage A, Stage-B branches, TEF 1,000)."""
    out: dict[str, dict[str, Any]] = {}
    cells = [(c, s, FEAS_BRANCHES) for s in FEAS_SEEDS for c in FEAS_CONFIGS] + [
        (FEAS_SSMAX[0], FEAS_SSMAX[1], FEAS_SSMAX[2])]
    for cfg, seed, branches in cells:
        stem = f"S2_{FEAS_SCALE}_{cfg}_s{seed}"
        model = f"configs/model/{FEAS_SCALE}/{cfg}.yaml"
        a = f"{stem}_A.yaml"
        out[a] = {"notes": f"plan S2-F384-{cfg}-s{seed}-A: FEAS Stage A, 0.3B tokens, provisional eta",
                  "exp_stage": "S2", "model": model, "training": "configs/training/stage_A.yaml",
                  "seed_index": seed, "lr": FEAS_LR, "steps_option": "FEAS",
                  "overrides": {"gdiv.fallback_lr": FEAS_FALLBACK_LR}}
        for br in branches:
            b = f"{stem}_{_bname(br)}.yaml"
            out[b] = {"notes": f"plan S2-F384-{cfg}-s{seed}-{_bname(br)}: Stage-B branch {br} tokens from the Stage-A final",
                      "exp_stage": "S2", "model": model, "training": "configs/training/stage_B.yaml",
                      "seed_index": seed, "lr": FEAS_LR, "steps_option": br, "parent": f"{FEAS_DIR}/{a}"}
            t = f"{stem}_{_bname(br)}_T.yaml"
            out[t] = {"notes": (f"plan S2-F384-{cfg}-s{seed}-{_bname(br)}-T: TEF 1,000 steps (90/10, answer_norm block "
                                "per D063); LM-2 at TEF start (= before TEF) and at 250/500/1000"),
                      "exp_stage": "S2", "model": model, "training": "configs/training/tef.yaml",
                      "seed_index": seed, "parent": f"{FEAS_DIR}/{b}",
                      "overrides": {"validation.at_start": True}}
    return out


def feas_design() -> list[dict[str, Any]]:
    """One row per FEAS TEF run YAML: the design cell the DTS-10 decision code keys on."""
    rows = []
    for name, doc in feas_run_docs().items():
        if not name.endswith("_T.yaml"):
            continue
        cfg = doc["model"].rsplit("/", 1)[1][:-5]
        rows.append({"yaml": f"{FEAS_DIR}/{name}", "config": cfg, "k": 0 if cfg == "C0" else 12,
                     "arm": "ssmax" if cfg.endswith("ssmax") else "plain", "seed": doc["seed_index"],
                     "branch": name.split("_")[-2].replace("B0", "").lstrip("0") + "M", "scale": FEAS_SCALE})
    return rows


def render_run(doc: dict[str, Any]) -> str:
    return FEAS_HEADER + yaml.safe_dump(doc, sort_keys=False, default_flow_style=False, width=120)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default=str(REPO_ROOT / "configs" / "model"))
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--feas-out", default=str(REPO_ROOT / FEAS_DIR))
    a = ap.parse_args(argv)
    out = Path(a.out)
    stale = []
    n = 0
    for scale in SCALES:
        for name, tier, ov in NAMED:
            text = render(model_doc(scale, name, tier, ov))
            p = out / scale / f"{name}.yaml"
            n += 1
            if a.check:
                if not p.is_file() or p.read_text() != text:
                    stale.append(str(p))
                continue
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(text)
    feas_out = Path(a.feas_out)
    docs = feas_run_docs()
    for name, doc in docs.items():
        text = render_run(doc)
        p = feas_out / name
        if a.check:
            if not p.is_file() or p.read_text() != text:
                stale.append(str(p))
            continue
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
    if feas_out.is_dir():
        extra = sorted(str(q) for q in feas_out.glob("*.yaml") if q.name not in docs)
        if extra:
            stale.extend(f"{q} (not generated)" for q in extra)
    if a.check:
        if stale:
            print("stale/missing generated configs:\n  " + "\n  ".join(stale))
            return 1
        print(f"all {n} model configs and {len(docs)} FEAS run YAMLs up to date")
        return 0
    print(f"wrote {n} model configs under {out} and {len(docs)} FEAS run YAMLs under {feas_out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
